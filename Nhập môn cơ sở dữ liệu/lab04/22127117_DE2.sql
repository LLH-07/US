SELECT TC.DIADIEM
FROM TOCHUC TC
JOIN HOINGHI HN
ON TC.HOINGHI = HN.MAHOINGHI
WHERE HN.TENHOINGHI = N'Tri thức và dữ liệu' and TC.NAMTOCHUC = 2023



SELECT HN.TENHOINGHI, HN.QUOCGIA
FROM HOINGHI HN
JOIN TOCHUC TC
ON HN.MAHOINGHI = TC.HOINGHI
JOIN BAIBAO BB
ON TC.HOINGHI = BB.CHUDE and TC.NAMTOCHUC = BB.NAMTOCHUC
WHERE TC.DIADIEM like '%Nhật Bản%'
	  and BB.CHUDE = N'Nghiên cứu'
	  and NOT EXISTS (
		SELECT *
		FROM BAIBAO
		WHERE BB.LOAIBAIBAO = N'Toàn văn' and BB.CHUDE = N'Ứng dụng')





SELECT HN.MAHOINGHI, HN.TENHOINGHI, TC.NAMTOCHUC, COUNT(BB.STT) AS SoLuongBaiBao
FROM HOINGHI HN
JOIN  TOCHUC TC 
ON HN.MAHOINGHI = TC.HOINGHI
LEFT JOIN BAIBAO BB 
ON TC.HOINGHI = BB.HOINGHI AND TC.NAMTOCHUC = BB.NAMTOCHUC
GROUP BY HN.MAHOINGHI, HN.TENHOINGHI, TC.NAMTOCHUC
ORDER BY HN.MAHOINGHI, TC.NAMTOCHUC;
