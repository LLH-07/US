CREATE DATABASE QLHOINGHI
GO

USE QLHOINGHI
GO


CREATE TABLE BAIBAO (
	STT INT,
	HOINGHI VARCHAR(5),
	NAMTOCHUC INT,
	LOAIBAIBAO NVARCHAR(15),
	CHUDE NVARCHAR(15)

	CONSTRAINT PK_BAIBAO
	PRIMARY KEY (STT, HOINGHI, NAMTOCHUC)
)

CREATE TABLE HOINGHI (
	MAHOINGHI VARCHAR(5),
	QUOCGIA NVARCHAR(50),
	TENHOINGHI NVARCHAR(50),
	NAMTHANHLAP INT,
	NHAXUATBAN NVARCHAR(50)

	CONSTRAINT PK_HOINGHI
	PRIMARY KEY (MAHOINGHI)
)

CREATE TABLE TOCHUC (
	HOINGHI VARCHAR(5),
	NAMTOCHUC INT,
	DIADIEM NVARCHAR (50),
	BAIBAOTIEUBIEU INT

	CONSTRAINT PK_TOCHUC
	PRIMARY KEY (HOINGHI, NAMTOCHUC)
)


ALTER TABLE BAIBAO
ADD
	CONSTRAINT FK_BB_TC
	FOREIGN KEY (HOINGHI, NAMTOCHUC)
	REFERENCES TOCHUC,

	CONSTRAINT CK_BB
	CHECK (LOAIBAIBAO = N'Toàn văn' OR LOAIBAIBAO = N'Tóm tắt')


ALTER TABLE HOINGHI
ADD
	CONSTRAINT DF_NTL
	DEFAULT YEAR(GETDATE()) FOR NAMTHANHLAP


ALTER TABLE TOCHUC
ADD
	CONSTRAINT FK_TC_HN
	FOREIGN KEY (HOINGHI)
	REFERENCES HOINGHI,

	CONSTRAINT FK_TC_BB
	FOREIGN KEY (BAIBAOTIEUBIEU, HOINGHI, NAMTOCHUC)
	REFERENCES BAIBAO,

	CONSTRAINT DF_HN
	DEFAULT NULL FOR HOINGHI,

	CONSTRAINT DF_NTC
	DEFAULT NULL FOR NAMTOCHUC 


