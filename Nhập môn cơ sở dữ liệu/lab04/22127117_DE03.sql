CREATE DATABASE DiemThamQuan
GO

USE DiemThamQuan
GO

CREATE TABLE TINHTHANH (
	QUOCGIA CHAR(5),
	MATINHTHANH CHAR(5),
	TENTT NVARCHAR(30),
	DANSO INT,
	DIENTICH FLOAT

	CONSTRAINT PK_TINHTHANH
	PRIMARY KEY (QUOCGIA, MATINHTHANH)
)

CREATE TABLE DIEMTHAMQUAN (
	MADTQ VARCHAR(10),
	TENDTQ NVARCHAR(30),
	TINHTHANH CHAR(5),
	QUOCGIA CHAR(5),
	DACDIEM NVARCHAR(50)

	CONSTRAINT PK_DIEMTHAMQUAN
	PRIMARY KEY (MADTQ)
)

CREATE TABLE QUOCGIA (
	MAQG CHAR(5),
	TENQG NVARCHAR(20),
	THUDO CHAR(5),
	DANSO INT,
	DIENTICH FLOAT

	CONSTRAINT PK_QUOCGIA
	PRIMARY KEY (MAQG)
)

