SELECT DTQ.MADTQ, DTQ.TENDTQ
FROM DIEMTHAMQUAN DTQ
JOIN TINHTHANH TT
ON DTQ.TINHTHANH = TT.MATINHTHANH AND DTQ.QUOCGIA = TT.QUOCGIA
JOIN QUOCGIA QG
ON TT.QUOCGIA = QG.MAQG
WHERE TT.DIENTICH > QG.DIENTICH / 100


