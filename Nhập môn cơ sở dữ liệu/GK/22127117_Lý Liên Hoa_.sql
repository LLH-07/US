SELECT DISTINCT KS.TENKS, KS.XEPHANG
FROM KHACHSAN KS
JOIN SANHTIEC ST
ON KS.MAKS = ST.MAKS
WHERE ST.GIATHUE >= 5000 and ST.GIATHUE <= 7000

-- Q4:
SELECT KS.TENKS, CN.DIACHI
FROM KHACHSAN KS
JOIN CHINHANH CN
ON KS.MAKS = CN.MAKS
JOIN SANHTIEC ST
ON CN.MACN = ST.MACN and CN.MAKS = ST.MAKS
WHERE KS.XEPHANG < 5 

-- Q5:
SELECT KS.TENKS, COUNT(CN.MACN) AS SoLuongChiNhanh
FROM KHACHSAN KS
LEFT JOIN CHINHANH CN
ON KS.MAKS = CN.MACN
JOIN SANHTIEC ST
ON CN.MACN = ST.MACN and CN.MAKS = ST.MAKS
GROUP BY KS.TENKS, CN.MACN
HAVING MIN(ST.SUCCHUA) >= 500

