CREATE TABLE KHACHSAN (
	MAKS VARCHAR(5),
	TENKS NVARCHAR(20) UNIQUE NOT NULL,
	NAMTHANHLAP INT DEFAULT YEAR(GETDATE()),
	XEPHANG INT

	CONSTRAINT PK_KHACHSAN
	PRIMARY KEY (MAKS),
	
	CONSTRAINT CK_KHACHSAN
	CHECK (XEPHANG >= 1 and XEPHANG <=5)
)

CREATE TABLE CHINHANH (
	MACN VARCHAR(5),
	MAKS VARCHAR(5),
	DIACHI NVARCHAR(50),
	SANHTIECCHINH VARCHAR(5) DEFAULT NULL

	CONSTRAINT PK_CHINHANH
	PRIMARY KEY (MACN, MAKS)
)

CREATE TABLE SANHTIEC (
	MASANH VARCHAR(5),
	MACN VARCHAR(5),
	MAKS VARCHAR(5),
	TENSANH NVARCHAR(30),
	SUCCHUA INT,
	GIATHUE INT DEFAULT 5000

	CONSTRAINT PK_SANHTIEC
	PRIMARY KEY (MASANH, MACN, MAKS),

	CONSTRAINT CK_SANHTIEC
	CHECK (SUCCHUA > 0)
)


