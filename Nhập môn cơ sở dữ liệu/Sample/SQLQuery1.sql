--B2: Tạo tất cả các bảng & PK & CK & DF & UK
--Kiểu dữ liệu
	--Chuỗi:
		--Không dấu: CHAR, VARCHAR
		--Có dấu: NCHAR, NVARCHAR
	--Số: INT, FLOAT, DOUBLE, MONEY, DECIMAL(P,S)
	--Ngày: DATE

CREATE TABLE SACH
(
	MASACH CHAR(4),
	TENSACH NVARCHAR(50),
	SOLUONG INT,
	DONGIA INT,
	MALOAI CHAR(2),
	KHTIEUBIEU INT

	CONSTRAINT PK_SACH
	PRIMARY KEY(MASACH)
	--Khai báo check CONSTRAINT: SOLUONG > 0
	CONSTRAINT CK_SOLUONG
	CHECK(SOLUONG > 0 and SOLUONG < 5)  
)
CREATE TABLE KHACHHANG
(
	MALOAI CHAR(2),
	STT INT,
	HOTEN NVARCHAR(50),
	DIACHI NVARCHAR(100),
	KHPHUTHUOC INT

	CONSTRAINT PK_KH
	PRIMARY KEY (MALOAI, STT)
)
CREATE TABLE MUAHANG
(
	LOAIKH CHAR(2),
	SOTT INT,
	MASACH CHAR(4),
	NGAYMUA DATE,
	SOLUONG INT,
	DONGIA INT

	CONSTRAINT PK_MH
	PRIMARY KEY(LOAIKH, SOTT, MASACH, NGAYMUA)
)

--B3: Tạo liên kết (Khóa ngoại)
ALTER TABLE KHACHHANG
ADD
	CONSTRAINT FK_KH_KH
	FOREIGN KEY (MALOAI,KHPHUTHUOC)
	REFERENCES KHACHHANG
ALTER TABLE SACH
ADD
	CONSTRAINT FK_S_KH
	FOREIGN KEY (MALOAI,KHTIEUBIEU)
	REFERENCES KHACHHANG
ALTER TABLE MUAHANG
ADD
	CONSTRAINT FK_MH_KH
	FOREIGN KEY (LOAIKH,SOTT)
	REFERENCES KHACHHANG,
	CONSTRAINT FK_MH_S
	FOREIGN KEY (MASACH)
	REFERENCES SACH

